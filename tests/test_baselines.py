import json
from pathlib import Path

import pytest

from src.evaluation.metrics import evaluate_prediction, exact_match_score, f1_score
from src.generation.cache import GenerationCache
from src.retrieval.indexer import ChromaRetriever


def test_exact_match_metric():
    assert exact_match_score("Arthur's Magazine", "arthurs magazine") == 1.0
    assert exact_match_score("The United States of America", "united states of america") == 1.0
    assert exact_match_score("A quick brown fox", "quick brown fox") == 1.0
    assert exact_match_score("Paris", "London") == 0.0


def test_token_f1_metric():
    assert f1_score("University of California, Berkeley", "UC Berkeley") > 0.0
    assert f1_score("apple orange banana", "apple banana") == pytest.approx(0.8, rel=1e-2)
    assert f1_score("completely different", "unrelated tokens") == 0.0
    # Test multi-ground-truth evaluation
    eval_res = evaluate_prediction("New York City", ["NYC", "New York", "City of New York"])
    assert eval_res["em"] == 1.0 or eval_res["f1"] > 0.6


def test_generation_cache(tmp_path):
    test_db = tmp_path / "test_cache.sqlite"
    cache = GenerationCache(db_path=str(test_db))

    key = cache.make_key("What is AI?", 3, ["AI is artificial intelligence."])
    assert cache.get(key) is None

    cache.set(
        cache_key=key,
        query="What is AI?",
        k=3,
        answer="artificial intelligence",
        tokens_in=25,
        tokens_out=4,
        latency_ms=12.5,
        metadata={"test": True},
    )

    cached = cache.get(key)
    assert cached is not None
    assert cached["answer"] == "artificial intelligence"
    assert cached["tokens_in"] == 25
    assert cached["tokens_out"] == 4
    assert cached["cached"] is True
    assert cache.count() == 1


def test_retriever_interface():
    retriever = ChromaRetriever()
    assert retriever.count() > 0

    # k=0 should return empty list without querying vector DB
    res_0 = retriever.retrieve("Any query here", k=0)
    assert res_0 == []

    # k=3 should return exactly 3 passages with valid schema
    res_3 = retriever.retrieve("magazine publisher", k=3)
    assert len(res_3) == 3
    for p in res_3:
        assert "id" in p
        assert "title" in p
        assert "text" in p
        assert "score" in p
        assert len(p["text"]) > 0


def test_baselines_results_file():
    results_path = Path("results/baselines.json")
    assert results_path.exists(), "baselines.json must be generated by run_baselines.py"

    with open(results_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    for k in [0, 3, 5, 10]:
        key = f"k_{k}"
        assert key in data, f"Missing {key} in baselines.json"
        summary = data[key]["summary"]
        assert summary["k"] == k
        assert "em" in summary
        assert "f1" in summary
        assert "avg_tokens" in summary
        assert "p50_latency_ms" in summary
        assert summary["queries_count"] > 0
